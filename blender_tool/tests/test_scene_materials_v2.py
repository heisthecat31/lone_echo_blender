def _channel(tex: str, role: str, dxgi: int, subdir: str = "T") -> dict:
    """A channel exactly as `le_mesh.materials._channel` + build_material_spec
    emit it — built through the real module so the fixture cannot drift from the
    producer."""
    ch = dict(M._channel(role, tex, {tex: dxgi}))
    ch["file"] = f"{subdir}/{tex}.dds"
    return ch


def _spec(key="shd__mat", *, role_textures=None, dxgi=None, scalars=None,
          subdir="T") -> dict:
    """A spec built by THE producer (`build_material_spec`) — same call the
    extractor makes — so this file tests the contract, not a copy of it."""
    role_textures = role_textures or {}
    dxgi = dxgi or {}
    shd, _, mat_hash = key.partition("__")
    return M.build_material_spec(
        key, shaderset_hash=shd, material_hash=mat_hash,
        role_textures=role_textures, dxgi_by_tex=dxgi, scalars=scalars or {},
        texture_files={t: f"{subdir}/{t}.dds" for t in role_textures.values()})


