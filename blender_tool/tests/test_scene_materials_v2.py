def test_v1_projection_matches_the_v2_spec_it_came_from():
    """`_v1_entry` must be a projection, so v1 and v2 can never disagree."""
    from unittest import SkipTest                      # noqa: PLC0415
    try:
        from le_scene_materials import _v1_entry       # noqa: PLC0415
    except ImportError as exc:                         # pragma: no cover
        # `scripts/le_scene_materials.py` pulls in the Oodle-backed decode stack
        # at import time, which a checkout without `pyoodle` cannot satisfy.
        raise SkipTest(
            f"scripts/le_scene_materials.py is not importable here ({exc}). "
            "`pip install pyoodle` (or check it out beside this repository) to "
            "enable it. ⛔ WHILE THIS SKIP IS ACTIVE THE v1 SIDECAR PROJECTION "
            "IS UNVERIFIED.")

    doc = _synthetic_v2()
    entry = doc["materials"][0]
    v1 = _v1_entry(entry, {"aa00000000000001": ["deadbeefdeadbeef", 0, 0, 0]})
    assert set(v1) == V1_FIELDS
    spec = entry["spec"]
    assert v1["mattype"] == spec["mattype"]
    assert v1["double_sided"] == spec["double_sided"]
    assert v1["basecolor_texture"] == spec["channels"]["base_color"]["texture"]
    assert v1["basecolor_role"] == spec["channels"]["base_color"]["role_key"]
    assert v1["basecolor_dds"] == spec["channels"]["base_color"]["file"]
    assert v1["normal_texture"] == spec["channels"]["normal"]["texture"]
    assert v1["owning_archive"] == "deadbeefdeadbeef"


