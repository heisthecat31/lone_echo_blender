"""The LEVEL material sidecar `<master>_materials.json` — schema v2.

Pure stdlib: no `bpy`, no Oodle, no archive load. Two halves:

  * SYNTHETIC — a hand-built v2 envelope and a hand-built v1 envelope, so the
    contract is locked deterministically even in a fresh clone (the real
    artifacts live under `blender_tool/exports/`, which is NOT tracked by git).
  * REAL — the same invariants re-run against
    `blender_tool/exports/942c829457a04a62_materials.json` (station_front, 1050
    meshes / 21394 instances) when it is present, plus the station_front-specific
    floors. Absent file => every test in that half raises `unittest.SkipTest`
    with a reason naming the artifact, never a silent PASS of the synthetic
    half.

WHY THIS FILE EXISTS
--------------------
The single-mesh `.lemesh` path carries a 35-field material spec (alpha /
render_mode, emissive layer+tint+intensity, specular, roughness_is_sqrt,
ao_channel, layer blends, mattype/blendmode, flags, named scalars, and a
`channels` dict of resolved texture roles). The level path emitted 11 flat
fields and 2 texture channels — a whole generation behind, so none of the
alpha / emissive / specular / roughness / blend-mask / AO / colorspace /
alpha_mode work reached a level render. v2 carries the spec VERBATIM: the
consumer calls `material_builder.build_material(spec, tex_base, opts)` with
zero adaptation, and this file is what stops it drifting again.
"""

