def _check_v2_envelope(doc: dict, label: str) -> None:
    assert set(doc) == V2_ENVELOPE_KEYS, f"{label}: envelope keys {sorted(doc)}"
    assert doc["version"] == SIDECAR_VERSION, f"{label}: version {doc['version']}"
    assert isinstance(doc["master"], str) and len(doc["master"]) == 16, label
    assert isinstance(doc["textures_subdir"], str) and doc["textures_subdir"], label
    assert isinstance(doc["materials"], list) and doc["materials"], label
    for entry in doc["materials"]:
        assert set(entry) == {"matidx", "shdidx", "spec"}, f"{label}: {sorted(entry)}"
        assert isinstance(entry["matidx"], int) and isinstance(entry["shdidx"], int)
        assert isinstance(entry["spec"], dict)


def _check_specs_are_builder_ready(doc: dict, label: str) -> None:
    subdir = doc["textures_subdir"]
    for entry in doc["materials"]:
        spec = entry["spec"]
        missing = [k for k in BUILDER_SPEC_KEYS if k not in spec]
        assert not missing, f"{label}: spec {spec.get('key')} missing {missing}"
        # key format is le_extract.material_key's: "<shaderset>__<material>"
        if spec["shaderset_hash"] and spec["material_hash"]:
            assert spec["key"] == f"{spec['shaderset_hash']}__{spec['material_hash']}", label
        assert isinstance(spec["channels"], dict)
        assert isinstance(spec["layers"], list)
        assert spec["render_mode"] in (M.RENDER_MODE_OPAQUE, M.RENDER_MODE_CLIP,
                                       M.RENDER_MODE_BLEND), label
        for name, ch in spec["channels"].items():
            for k in CHANNEL_KEYS:
                assert k in ch, f"{label}: channel {name} missing {k}"
            # paths are SIDECAR-relative, mirroring .lemesh's textures/ subdir
            assert ch["file"] == "" or ch["file"].startswith(subdir + "/"), \
                f"{label}: channel {name} file {ch['file']!r} not under {subdir}/"
            assert ch["colorspace"] in ("sRGB", "Non-Color"), label
            assert ch["alpha_mode"] in (M.ALPHA_MODE_CHANNEL_PACKED,
                                        M.ALPHA_MODE_STRAIGHT,
                                        M.ALPHA_MODE_NONE), label
            assert ch["alpha_is_linear"] is True, label


def _check_role_names_are_real(doc: dict, label: str) -> None:
    """⛔ Ten role names were fabricated once. Every routed role_key must be a
    cracked `INPUTNAME_ROLE` name (or an explicit `unknown_s{slot}` placeholder)
    — never an invented one."""
    for entry in doc["materials"]:
        for name, ch in entry["spec"]["channels"].items():
            rk = ch["role_key"]
            assert rk in M.KNOWN_ROLES or rk.startswith("unknown_s"), \
                f"{label}: fabricated role name {rk!r} on channel {name}"


def _check_coherence(doc: dict, label: str) -> tuple[int, int]:
    bad = []
    for entry in doc["materials"]:
        spec = entry["spec"]
        pair = (spec.get("mattype_name") or "", spec.get("blend_mode_name") or "")
        # a name pair must at minimum be self-consistent with the numeric fields
        assert M.MATTYPE_NAMES.get(int(spec["mattype"]), "") == pair[0], label
        assert M.BLENDMODE_NAMES.get(int(spec["blend_mode"]), "") == pair[1], label
        if pair not in COHERENT_PAIRS:
            bad.append((spec.get("key"), pair))
    return len(doc["materials"]) - len(bad), len(doc["materials"])


def _channel_histogram(doc: dict) -> dict:
    hist: dict = {}
    for entry in doc["materials"]:
        for name in entry["spec"]["channels"]:
            hist[name] = hist.get(name, 0) + 1
    return hist


def _load_real() -> dict | None:
    """The real station_front sidecar, or None when it is absent / not v2.

    `blender_tool/exports/` is not tracked by git, so a fresh clone legitimately
    has no artifact and the REAL half becomes a no-op. A file that IS present but
    is not v2 is a REGRESSION, not an absence — `test_real_sidecar_is_v2` fails
    loudly on it, and the remaining real tests stay quiet so one root cause does
    not print as five failures.
    """
    if not REAL_SIDECAR.exists():
        return None
    doc = json.loads(REAL_SIDECAR.read_text(encoding="utf-8"))
    return doc if doc.get("version") == SIDECAR_VERSION else None


def test_real_sidecar_is_v2():
    """A sidecar on disk must be v2 — a v1 file means the artifact is stale."""
    if not REAL_SIDECAR.exists():
        raise SkipTest(
            f"{REAL_SIDECAR.name} is absent — `blender_tool/exports/` is "
            f"gitignored extracted game data, so a clean checkout has none. "
            f"Write it with `python.exe scripts/le_scene_materials.py "
            f"{REAL_MASTER} --manifest blender_tool/exports/{REAL_MASTER}"
            f".lescatter/manifest.json --out-textures blender_tool/exports/"
            f"{REAL_MASTER}_textures --out-json {REAL_SIDECAR}` to make this "
            f"test able to run. ⛔ WHILE THIS SKIP IS ACTIVE NOTHING DETECTS A "
            f"STALE v1 LEVEL MATERIAL SIDECAR ON DISK.")
    doc = json.loads(REAL_SIDECAR.read_text(encoding="utf-8"))
    assert doc.get("version") == SIDECAR_VERSION, (
        f"{REAL_SIDECAR.name} is schema v{doc.get('version', 1)}, expected v2 — "
        "regenerate with scripts/le_scene_materials.py")


